import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

// The related-repo closer is a plain workflow with a script, not a gh-aw definition and not a model run
// (record 0026). On frodo-lib#806 the model named the closed issue itself as the original and the write to the
// other repository was refused, so the original (frodo-cli#922) was never updated. What the script decides is
// pinned in scripts/related-repo-closer.test.mjs; this pins the workflow around it: when it starts, what it may
// do with the workflow's own token, where the token for the other repository comes from, and that everything
// the script imports is installed with it.

const REPO = new URL('..', import.meta.url);
const read = (p) => fs.readFileSync(new URL(p, REPO), 'utf8');
const exists = (p) => fs.existsSync(new URL(p, REPO));
const workflow = read('workflows/related-repo-closer.yml');
const manifest = read('aw.yml');
const flat = (s) => s.replace(/\s+/g, ' ');

test('it is a plain workflow: no gh-aw definition, no engine, no model', () => {
  assert.equal(exists('workflows/related-repo-closer.md'), false, 'the model-based closer is gone');
  assert.doesNotMatch(workflow, /^engine:|^safe-outputs:|^tools:|max-ai-credits|copilot/m);
  assert.match(workflow, /^# Related-repo closer\. Plain GitHub Actions, no LLM\./);
});

test('it starts on a closed issue, or by hand for one issue with an optional dry run', () => {
  assert.match(workflow, /^on:\n {2}issues:\n {4}types: \[closed\]\n {2}workflow_dispatch:\n {4}inputs:\n {6}issue_number:\n(?: {8}.*\n)*? {8}required: true\n/m);
  assert.match(workflow, / {6}dry_run:\n(?: {8}.*\n)*? {8}type: boolean\n {8}default: false\n/);
  assert.match(workflow, /^name: "Concierge 4b ▸ Related Repo Closer"$/m, 'the marker is on the workflows that can be run by hand');
});

test('the workflow token may read, and nothing more: the writes use the other repository\'s token', () => {
  assert.match(workflow, /^permissions:\n {2}contents: read\n {2}issues: read\n\n/m);
  assert.doesNotMatch(workflow, /: write\b/);
});

test('the token for the other repository is generated by the updater, never written into the source', () => {
  assert.equal((workflow.match(/# concierge:cross-repo-env/g) ?? []).length, 1, 'one marker, in the step environment');
  assert.doesNotMatch(workflow, /secrets\./, 'a secret name in the source would be the same in every deployment');
  assert.doesNotMatch(workflow, /CROSS_REPO(_TOKEN)?:/, 'the generated lines are not in the source');
  assert.match(workflow, /GH_TOKEN: \$\{\{ github\.token \}\}\n(?: {10}.*\n)*? {10}# concierge:cross-repo-env\n {8}run:/);
});

test('every close is looked at only for the link label; the script checks the rest', () => {
  const condition = workflow.match(/^ {4}if: (.*)$/m)?.[1] ?? '';
  assert.match(condition, /contains\(github\.event\.issue\.labels\.\*\.name, 'original-in-related-repo'\)/);
  assert.match(condition, /github\.event_name == 'workflow_dispatch'/);
  assert.match(condition, /github\.event\.issue\.user\.type != 'Bot'/);
});

test('one run per issue at a time, and a run is never cancelled half way through its writes', () => {
  assert.match(workflow, /^concurrency:\n {2}group: related-repo-closer-\$\{\{ github\.event\.issue\.number \|\| inputs\.issue_number \}\}\n {2}cancel-in-progress: false$/m);
});

test('it runs the installed script, and a dry run is passed on', () => {
  assert.match(workflow, /run: node \.github\/scripts\/related-repo-closer\.mjs \$\(\[ "\$DRY_RUN" = "true" \] && echo --dry-run\)/);
  assert.match(workflow, /DRY_RUN: \$\{\{ inputs\.dry_run \}\}/);
});

test('the checkout is pinned like the other plain workflows', () => {
  const pinned = (file) => read(file).match(/uses: (actions\/checkout@[0-9a-f]{40}) # v[\d.]+/)?.[1];
  assert.ok(pinned('workflows/related-repo-closer.yml'));
  assert.equal(pinned('workflows/related-repo-closer.yml'), pinned('workflows/reporter-notify.yml'));
});

test('the workflow, its script and everything the script imports are installed together', () => {
  const script = read('scripts/related-repo-closer.mjs');
  for (const f of ['workflows/related-repo-closer.yml', 'scripts/related-repo-closer.mjs']) {
    assert.match(manifest, new RegExp(`^  - ${f.replace(/[.]/g, '\\.')}$`, 'm'), `${f} is not in aw.yml`);
  }
  assert.doesNotMatch(manifest, /related-repo-closer\.md/);
  for (const [, dep] of script.matchAll(/from '\.\/([\w-]+\.mjs)'/g)) {
    assert.match(manifest, new RegExp(`^  - scripts/${dep.replace(/[.]/g, '\\.')}$`, 'm'), `${dep} is imported by the closer but not installed`);
  }
  assert.match(flat(workflow.replace(/^#\s?/gm, '')), /it imports dependency-watch\.mjs and reporter-notify\.mjs, which imports janitor\.mjs: install them too/);
});

test('the script never decides by a model: no network call but the GitHub API, no process but gh', () => {
  const script = read('scripts/related-repo-closer.mjs');
  assert.doesNotMatch(script, /\bfetch\(|https?:\/\/|copilot|openai|anthropic/i);
  assert.deepEqual([...script.matchAll(/execFileSync\('([^']+)'/g)].map((m) => m[1]), ['gh']);
});
